#!/usr/bin/env bash
# Build the provider's document page and copy it into the provider's repo.
#   scripts/export-doc-view.sh ../pocpod0/infra/css/doc-view
# The copy carries the kit commit it came from; edit the kit, never the copy.
set -euo pipefail
dest="${1:?usage: $0 <destination dir>}"
cd "$(dirname "$0")/.."
npm run --silent build:doc-view
mkdir -p "$dest"
cp dist-doc-view/doc-view.js dist-doc-view/doc-view.css "$dest/"
sha="$(git rev-parse --short HEAD)$(git diff --quiet || echo '-dirty')"
echo "Generated by solid-kit@$sha (scripts/export-doc-view.sh). Do not edit; rebuild from the kit." > "$dest/SOURCE"
echo "doc-view: solid-kit@$sha -> $dest"
